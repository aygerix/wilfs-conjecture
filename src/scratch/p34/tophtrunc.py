"""TOPH / TM on a truncated semigroup S = <m, G> u [c, inf) (lead, 2026-10-20).
Full lex tile: left generators G (minimal) then right primitives (Apery elements of S in [c, c+m) not generated).
Reports W, Phat, TOPH slack m(W - Phat) = (N+1)m(m-1)/2 - sum_{Yhat}(|y|+N)(phi-c), and the TM slack at lambda = -c.
Usage: python tophtrunc.py m c g1 g2 ..."""
import sys
m, c = int(sys.argv[1]), int(sys.argv[2]); G = sorted(map(int, sys.argv[3:]))
T = c + m; INF = 10**18
S = bytearray(T); S[0] = 1
for x in range(1, T):
    if x >= c or (x >= m and S[x - m]) or any(g <= x and S[x - g] for g in G): S[x] = 1
assert not S[c - 1]
Ap = [x for x in range(T) if S[x] and (x < m or not S[x - m])]
gensL = [g for g in G if not any(S[g - h] for h in [m] + G if h < g)]
n = len(gensL)
fac = {0: (0,) * n}
for x in Ap[1:]:
    if x >= c: continue
    best = None
    for i, g in enumerate(gensL):
        if x - g in fac:
            a = list(fac[x - g]); a[i] += 1; a = tuple(a)
            if best is None or a[::-1] < best[::-1]: best = a
    fac[x] = best
# top window: elements generated by left gens with phi in [c, c+m), else right primitives
right = []
for x in Ap:
    if x < c: continue
    best = None
    for i, g in enumerate(gensL):
        if x - g in fac and x - g < c:
            a = list(fac[x - g]); a[i] += 1; a = tuple(a)
            if best is None or a[::-1] < best[::-1]: best = a
    if best is None: right.append(x)
    else: fac[x] = best
r = len(right); N = n + r
g = sum(1 for x in range(c) if not S[x]); ell = c - g; W = (N + 1) * ell - c
M = {a: x for x, a in fac.items()}
up = lambda a, i: tuple(a[t] + (t == i) for t in range(n))
# Phat: left directions (early ends below c) + right-primitive directions (every beta != 0 below c ends at itself)
P = 0
for a, x in M.items():
    if x < c:
        for i in range(n):
            if up(a, i) not in M: P += (a[i] + 1) * (c - x)
        if any(a): P += r * (c - x)
top = sum((sum(a) + N) * (x - c) for a, x in M.items() if x >= c) + sum((1 + N) * (x - c) for x in right)
toph = (N + 1) * m * (m - 1) // 2 - top
# TM at lambda = -c: all maximal elements of the full tile (right primitives e_p are maximal; left part: no up-neighbour in M and phi+g >= ... )
mxsum = top
for a, x in M.items():
    if x < c and all(up(a, i) not in M for i in range(n)) and (r == 0 or not any(True for _ in [0]) or any(a)):
        if any(a) or r == 0: mxsum += (sum(a) + N) * ((x - c) % m)
tm = (N + 1) * m * (m - 1) // 2 - mxsum
print("m=%d c=%d n=%d r=%d N=%d W=%d  m*Phat=%d  m(W-Phat)=%d  TOPH slack=%d  TM slack(lambda=-c)=%d" % (m, c, n, r, N, W, P, m * W - P, toph, tm))
