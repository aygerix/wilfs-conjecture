"""IMaxCL test (lead, 2026-10-19): MaxCL for injective labelings with the deficiency bonus, multiplier
(d+1+BON*(m-|D|)); BON=1 is IMaxCL, BON=0 plain MaxCL (copy of maxcl_inj.py).  Original doc:
MaxCL without surjectivity.  D = random finite down-set in N^d (union of boxes generated by
random corners), m >= |D|, p in (Z/m)^d with x -> x.p mod m INJECTIVE on D.  For every sigma, r(x) = (x.p - sigma) mod m:
   MaxCL:  sum_{y in A} (|y|-1) r(y) <= (d+1) sum_{z in N} r(z)      (A = maximal cells of D, N = D \\ A).
Also tests the units-included variant where e_a in D for all a is required (as in tiles).  Reports failures and the
smallest failing instances (by |D|, then m).
usage: python imaxcl.py seed trials dmax hmax mslack [BON]"""
import sys, random, itertools


def downset(gens, d):
    D = set()
    for g in gens:
        for x in itertools.product(*[range(gi+1) for gi in g]): D.add(x)
    return sorted(D)


if __name__ == '__main__':
    seed, T, dmax, hmax, mslack = map(int, sys.argv[1:6]); BON = int(sys.argv[6]) if len(sys.argv) > 6 else 0; rng = random.Random(seed)
    fails = 0; n = 0; nt = 0; worst = None; smallest = None
    for t in range(T):
        d = rng.randint(1, dmax); gens = [tuple(1 if i == a else 0 for i in range(d)) for a in range(d)]
        for _ in range(rng.randint(1, 6)):
            h = rng.randint(1, hmax); g = [0]*d
            for _ in range(h): g[rng.randrange(d)] += 1
            gens.append(tuple(g))
        D = downset(gens, d)
        if len(D) < 3: continue
        m = len(D)+rng.randint(0, mslack)
        ok = False
        for _ in range(200):
            p = [rng.randrange(1, m) for _ in range(d)]
            vals = [sum(x[i]*p[i] for i in range(d)) % m for x in D]
            if len(set(vals)) == len(D): ok = True; break
        if not ok: continue
        n += 1; nt += (m == len(D))
        Dset = set(D)
        def add(x, a): return tuple(x[i]+(i == a) for i in range(d))
        A = [y for y in D if all(add(y, a) not in Dset for a in range(d))]; Aset = set(A)
        Nn = [x for x in D if x not in Aset]
        phi = {x: sum(x[i]*p[i] for i in range(d)) for x in D}
        for sig in range(m):
            r = {x: (phi[x]-sig) % m for x in D}
            s = (d+1+BON*(m-len(D)))*sum(r[x] for x in Nn)-sum((sum(y)-1)*r[y] for y in A)
            if worst is None or s < worst[0]: worst = (s, d, m, len(D), gens, p, sig)
            if s < 0:
                fails += 1
                key = (len(D), m)
                if smallest is None or key < smallest[0]: smallest = (key, d, gens, p, sig, s, D)
                if fails <= 5: print("FAIL d", d, "m", m, "|D|", len(D), "gens", gens, "p", p, "sigma", sig, "slack", s, flush=True)
                break
    print("instances", n, "(bijective:", nt, ") failing instances", fails, "worst", worst[:4], worst[5:])
    if smallest: print("smallest failure:", smallest[:6], "\n D =", smallest[6])
