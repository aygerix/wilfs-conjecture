out=[];n=0
for m,P,cells in DATA:
    sets={2:[],3:[]}
    for st in cells.split():
        z=tuple(i for i,ch in enumerate(st) for _ in range(int(ch)))
        sets[len(z)].append(z)
    bestS=bestH=None
    for sig in range(m):
        a=evaluate(m,[(u-sig)%m for u in P],sets[2],sets[3],(-sig)%m)
        n+=1
        if bestS is None or a['S']<bestS[0]:bestS=(a['S'],sig)
        if bestH is None or a['HC']<bestH[0]:bestH=(a['HC'],sig)
        assert a['S']>=0 and a['HC']>=0
    out.append(dict(m=m,P=P,minS=bestS,minHC=bestH))
