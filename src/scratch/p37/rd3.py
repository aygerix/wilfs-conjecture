r"""Targeted RD negation test (lead, 2026-10-21): S = <m, k1 m + a, k2 m + b> (and 4-generated lifts), all residues and
levels in range; T = <m, a, b>.  RD: W(S) >= W(T).  usage: python rd3.py mlo mhi K [four]"""
import sys, heapq
from math import gcd
def apery(m, G):
    w = [None] * m; w[0] = 0; h = [(0, 0)]; done = [False] * m
    while h:
        v, s = heapq.heappop(h)
        if done[s]: continue
        done[s] = True
        for x in G:
            t = (v + x) % m
            if w[t] is None or v + x < w[t]: w[t] = v + x; heapq.heappush(h, (v + x, t))
    return w
def W_of(m, G):
    w = apery(m, G); Ws = set(w); M = max(w)
    if M < m: return 0, 1   # T = N  (Frobenius < 0) handled by caller only if m is the multiplicity
    c = M - m + 1; g = sum(x // m for x in w)
    # minimal generators of the semigroup generated by m and G: Apery elements not sums of two nonzero Apery elements, plus m if minimal
    Ap = sorted(w)[1:]; Aps = set(Ap)
    gens = [x for x in Ap if not any((x - y) in Aps for y in Ap if y < x)]
    allg = sorted(set(gens + [m])); mu = min(allg)
    # m is a minimal generator iff m is not a sum of two nonzero elements: check via membership
    N = M + m; inS = [False] * (N + 1)
    for x in w:
        for z in range(x, N + 1, m): inS[z] = True
    mu = next(z for z in range(1, N + 1) if inS[z])
    gaps = [z for z in range(N + 1) if not inS[z]]
    if not gaps: return 0, 1
    c = gaps[-1] + 1; g = len(gaps)
    els = [z for z in range(1, c + mu + 1) if inS[z]]; Es = set(els)
    e = sum(1 for z in els if not any((z - y) in Es for y in els if y <= z // 2))
    return e * (c - g) - c, e
mlo, mhi, K = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3]); four = len(sys.argv) > 4
fails = 0; tested = 0; best = (10**9,)
for m in range(mlo, mhi + 1):
    for a in range(1, m):
        for b in range(a + 1, m):
            if gcd(gcd(m, a), b) != 1: continue
            WT, eT = W_of(m, [a, b])
            if WT <= 0: continue
            for k1 in range(1, K + 1):
                for k2 in range(1, K + 1):
                    G = [k1 * m + a, k2 * m + b]
                    WS, eS = W_of(m, G)
                    if eS != 3: continue   # a lifted generator is not minimal
                    tested += 1
                    if WS - WT < best[0]: best = (WS - WT, WS, WT, m, G)
                    if WS < WT:
                        fails += 1
                        if fails <= 10: print("RD FAIL S=<%d,%d,%d> W=%d  T=<%d,%d,%d> W(T)=%d" % (m, G[0], G[1], WS, m, a, b, WT), flush=True)
print("m=%d..%d K=%d tested %d (W(T)>0) RD failures %d; min W(S)-W(T) = %s" % (mlo, mhi, K, tested, fails, best))
