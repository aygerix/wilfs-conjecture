/* rdloc: local level-drop test over all numerical semigroups of genus <= G (lead, 2026-10-21).
 * For S with multiplicity m and a minimal generator g > m, let S' = <(minimal generators of S) with g replaced by g - m>.
 * Two kinds: g >= 2m (S' keeps multiplicity m; "high drop") and m < g < 2m (S' has multiplicity g - m; "low drop").
 * Test LD: W(S) >= W(S').  Reports failures with data.  usage: ./rdloc G [part nparts] */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define MX 128
static long nS[64], nH[64], nHf[64], nL[64], nLf[64], minH[64], minL[64]; static int G, Gsplit = 12, part = 0, np = 1; static long ctr = 0;
static void props(const unsigned char *in, int F, int *m, int *e, int *c, int *g, int *W, int *gens, int *ng){
  int cc = F + 1; *c = cc; int gg = 0, l = 0; for (int x = 0; x < cc; x++){ if (in[x]) l++; else gg++; } *g = gg;
  int mm = 0; for (int x = 1; x < MX; x++) if (in[x]){ mm = x; break; } *m = mm;
  int ee = 0; *ng = 0;
  for (int x = 1; x < cc + mm + 1 && x < MX; x++) if (in[x]){ int dec = 0; for (int y = 1; y <= x / 2 && !dec; y++) if (in[y] && in[x - y]) dec = 1;
      if (!dec){ ee++; gens[(*ng)++] = x; } }
  *e = ee; *W = (cc == 0) ? 0 : ee * l - cc;
}
static int Wgen(int *A, int na){
  /* W of the semigroup generated by A[0..na) (gcd 1 assumed) by membership up to a safe bound */
  int mu = A[0]; for (int i = 1; i < na; i++) if (A[i] < mu) mu = A[i];
  int w[MX], dn[MX]; for (int x = 0; x < mu; x++){ w[x] = 1 << 29; dn[x] = 0; } w[0] = 0;
  for (int it = 0; it < mu; it++){ int u = -1; for (int x = 0; x < mu; x++) if (!dn[x] && (u < 0 || w[x] < w[u])) u = x; dn[u] = 1;
    for (int j = 0; j < na; j++){ int v = w[u] + A[j], t = v % mu; if (v < w[t]) w[t] = v; } }
  int mx = 0; long gg = 0; for (int x = 0; x < mu; x++){ if (w[x] > mx) mx = w[x]; gg += w[x] / mu; }
  int c = mx - mu + 1; if (c <= 0) return 0;
  static unsigned char in[4 * MX]; int N = mx + mu + 1; for (int z = 0; z <= N; z++) in[z] = 0;
  for (int x = 0; x < mu; x++) for (int z = w[x]; z <= N; z += mu) in[z] = 1;
  int e = 0; for (int z = 1; z <= N; z++) if (in[z]){ int dec = 0; for (int y = 1; y <= z / 2 && !dec; y++) if (in[y] && in[z - y]) dec = 1; if (!dec) e++; }
  return (int)(e * (c - gg) - c);
}
static void visit(unsigned char *in, int F, int g){
  int m, e, c, gg, W, gens[MX], ng; props(in, F, &m, &e, &c, &gg, &W, gens, &ng);
  if (g > 0){
    nS[g]++;
    for (int i = 0; i < ng; i++){ if (gens[i] == m) continue; int A[MX]; for (int j = 0; j < ng; j++) A[j] = gens[j]; A[i] -= m;
      int W2 = Wgen(A, ng); int hi = gens[i] > 2 * m; long D = W - W2;
      if (hi){ nH[g]++; if (D < minH[g]) minH[g] = D; if (D < 0){ nHf[g]++; if (nHf[g] <= 3){ printf("HIGH-DROP FAIL g=%d W=%d W'=%d drop %d->%d S=<", g, W, W2, gens[i], gens[i] - m); for (int j = 0; j < ng; j++) printf("%s%d", j ? "," : "", gens[j]); printf(">\n"); fflush(stdout); } } }
      else { nL[g]++; if (D < minL[g]) minL[g] = D; if (D < 0){ nLf[g]++; if (nLf[g] <= 3){ printf("LOW-DROP FAIL g=%d W=%d W'=%d drop %d->%d S=<", g, W, W2, gens[i], gens[i] - m); for (int j = 0; j < ng; j++) printf("%s%d", j ? "," : "", gens[j]); printf(">\n"); fflush(stdout); } } }
    }
  }
  if (g == G) return;
  if (g == Gsplit){ if (ctr++ % np != part) return; }
  for (int i = 0; i < ng; i++){ int x = gens[i]; if (x <= F) continue; if (x + 1 >= MX - 2) continue;
    unsigned char ch[MX]; memcpy(ch, in, MX); ch[x] = 0; visit(ch, x, g + 1); }
}
int main(int argc, char **argv){
  G = atoi(argv[1]); if (argc > 3){ part = atoi(argv[2]); np = atoi(argv[3]); }
  for (int i = 0; i < 64; i++) minH[i] = minL[i] = 1L << 40;
  unsigned char in[MX]; for (int x = 0; x < MX; x++) in[x] = 1;
  visit(in, -1, 0);
  for (int g = 1; g <= G; g++) printf("genus %d part %d/%d: S=%ld high drops %ld fail %ld min %ld | low drops %ld fail %ld min %ld\n", g, part, np, nS[g], nH[g], nHf[g], nH[g] ? minH[g] : 0, nL[g], nLf[g], nL[g] ? minL[g] : 0);
  return 0;
}
